<h1>SubTube privacy policy</h1>
<p class="updated">Last updated 8 October 2026</p>

<p>
  SubTube shows new videos from the YouTube channels you subscribe to. It has no
  server of its own, and nothing you do in SubTube is sent to us.
</p>

<h2>What SubTube reads</h2>
<ul>
  <li>
    Your YouTube subscriptions and the public details of those channels' videos,
    through YouTube API Services. SubTube can't change anything on your YouTube
    account.
  </li>
  <li>
    The name and picture of your YouTube channel, to show which account is
    signed in.
  </li>
  <li>
    The name and email address of your Google account, to show which account is
    signed in.
  </li>
</ul>

<h2>What SubTube stores, and where</h2>
<ul>
  <li>
    Your filters, which videos you've watched and how far you've played each
    one, in a hidden folder in your own Google Drive that only SubTube can open.
    This is how they follow you between devices. SubTube can't see your other
    Drive files.
  </li>
  <li>A copy of the same on each device, so the app opens quickly.</li>
  <li>
    Each device deletes its own watched marks 30 days after it last loaded the
    video. A device you stop using keeps its marks in your Google Drive until
    you use Delete profile, which removes everything.
  </li>
  <li>Your Google sign-in, on the device only.</li>
</ul>

<h2>How your data is protected</h2>
<ul>
  <li>
    Everything SubTube reads travels straight between Google and your device
    over an encrypted connection.
  </li>
  <li>
    Your Google sign-in is kept by your device's own secure storage: the
    Keychain on Apple devices, Google Play services on Android, Chrome on the
    web.
  </li>
  <li>
    What SubTube saves in your Google Drive is protected by your Google account.
  </li>
</ul>

<h2>What SubTube doesn't do</h2>
<ul>
  <li>
    It has no accounts of its own, no analytics and no ads of its own. Your data
    is never sold or shared, because we never receive it.
  </li>
</ul>

<h2>YouTube and Google</h2>
<ul>
  <li>
    Videos play in YouTube's own player, so YouTube may collect data and show
    ads as it does on any site. Google's privacy policy applies:
    <a href="https://policies.google.com/privacy"
      >https://policies.google.com/privacy</a
    >. By using SubTube you also agree to the YouTube Terms of Service:
    <a href="https://www.youtube.com/t/terms">https://www.youtube.com/t/terms</a
    >. SubTube's own terms are at
    <a href="https://subtube.hafa.cc/terms">https://subtube.hafa.cc/terms</a>.
  </li>
  <li>
    SubTube's use of information received from Google APIs follows the Google
    API Services User Data Policy, including its Limited Use requirements.
  </li>
</ul>

<h2>Deleting your data</h2>
<ul>
  <li>
    Delete profile, in Settings, removes everything SubTube stored in your
    Google Drive and on that device.
  </li>
  <li>
    You can remove SubTube's access at any time at
    <a href="https://myaccount.google.com/permissions"
      >https://myaccount.google.com/permissions</a
    >.
  </li>
</ul>

